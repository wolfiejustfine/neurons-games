export function guideForLevel(id:SceneGameId,level:number):LearningGuide['steps'] {
  if(id==='alarms'){
    const lesson=clockLesson(level);
    if(!lesson.afternoon)return [
      'При ровном часе длинная стрелка стоит на 12.',
      'Короткая стрелка показывает час встречи.',
      'Перенеси часы к герою с нужным временем. Можно нажать на часы, затем на героя.',
    ];
    if(!lesson.halfHours)return [
      'После полудня час дня записывают как 13:00, два часа — 14:00.',
      'Короткая стрелка по-прежнему показывает 1, 2, 3 и так далее. Длинная стоит на 12.',
      'Подбери часы для каждой встречи.',
    ];
    return [
      'Длинная стрелка на 6 — это 30 минут, на 12 — ровный час.',
      'При получасе короткая стрелка между часами: между 1 и 2 — прошёл 1 час и ещё 30 минут.',
      'После полудня это 13:30. Перенеси часы к подходящей встрече.',
    ];
  }
  return GUIDES[id].steps;
}
